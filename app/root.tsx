function Document({
	children,
	nonce,
	theme = 'light',
	env = {},
	origin,
	path,
	isNativeShell = false,
}: {
	children: React.ReactNode
	nonce: string
	theme?: Theme
	env?: Record<string, string | undefined>
	origin?: string
	path?: string
	isNativeShell?: boolean
}) {
	const allowIndexing = ENV.ALLOW_INDEXING !== 'false'
	const launchTheme = launchThemes[theme]
	const posthogOrigin = env.POSTHOG_API_KEY
		? new URL(getPostHogHost(env.POSTHOG_HOST)).origin
		: null
	return (
		<html
			lang="en"
			className={`${theme} h-full overflow-x-hidden`}
			// The iOS app draws the page under the status bar; tailwind.css keys
			// the safe-area padding off this attribute.
			data-native-shell={isNativeShell ? '' : undefined}
		>
			<head>
				<meta charSet="utf-8" />
				<meta name="color-scheme" content="light dark" />
				<meta
					name="theme-color"
					content={launchThemes.light.canvas}
					media="(prefers-color-scheme: light)"
				/>
				<meta
					name="theme-color"
					content={launchThemes.dark.canvas}
					media="(prefers-color-scheme: dark)"
				/>
				<style
					nonce={nonce}
					data-pwa-launch-theme={theme}
					dangerouslySetInnerHTML={{
						__html: `:root{color-scheme:${theme}}html,body{background:${launchTheme.canvas};color:${launchTheme.foreground}}`,
					}}
				/>
				<ClientHintCheck nonce={nonce} />
				<Meta />
				{posthogOrigin ? (
					<link rel="preconnect" href={posthogOrigin} crossOrigin="anonymous" />
				) : null}
				<meta
					name="viewport"
					content={
						isNativeShell
							? 'width=device-width,initial-scale=1,viewport-fit=cover'
							: 'width=device-width,initial-scale=1'
					}
				/>
				<meta name="mobile-web-app-capable" content="yes" />
				<meta name="apple-mobile-web-app-capable" content="yes" />
				<meta name="apple-mobile-web-app-status-bar-style" content="default" />
				<meta name="apple-mobile-web-app-title" content="Quartermaster" />
				{allowIndexing ? null : (
					<meta name="robots" content="noindex, nofollow" />
				)}
				{origin && path ? (
					<link rel="canonical" href={`${origin}${path}`} />
				) : null}
				<Links />
			</head>
			<body className="bg-background text-foreground paper-grain">
				<a
					href="#main-content"
					className="focus:bg-card focus:shadow-warm-lg sr-only focus:not-sr-only focus:fixed focus:top-4 focus:left-4 focus:z-[100] focus:rounded-md focus:px-4 focus:py-2 focus:text-sm focus:font-medium"
				>
					Skip to content
				</a>
				{children}
				<script
					nonce={nonce}
					dangerouslySetInnerHTML={{
						__html: `window.ENV = ${JSON.stringify(env)}`,
					}}
				/>
				<ScrollRestoration nonce={nonce} />
				<Scripts nonce={nonce} />
			</body>
		</html>
	)
}

export function Layout({ children }: { children: React.ReactNode }) {
	// if there was an error running the loader, data could be missing
	const data = useLoaderData<typeof loader | null>()
	const nonce = useNonce()
	const theme = useOptionalTheme()
	// Marks the page as hydrated for the e2e tests. A parent's effects run
	// after its children's, so by now every mount effect on the page has run
	// and the router takes navigations. Error pages render inside this too.
	useEffect(() => {
		document.documentElement.dataset.hydrated = ''
	}, [])
	return (
		<Document
			nonce={nonce}
			theme={theme}
			env={data?.ENV}
			origin={data?.requestInfo.origin}
			path={data?.requestInfo.path}
			isNativeShell={data?.requestInfo.isNativeShell}
		>
			{children}
		</Document>
	)
}

function App() {
	const data = useLoaderData<typeof loader>()
	const user = useOptionalUser()
	const theme = useTheme()
	const isPro = data.tierInfo.isProActive
	const { pathname } = useLocation()
	const isNativeShell = data.requestInfo.isNativeShell
	// The homepage re-themes the chrome around it to espresso in either theme.
	const chrome = pathname === '/' ? 'espresso' : undefined
	useToast(data.toast)
	useNavDirection()
	useRecordHistory()
	useRefreshAfterTraversal()
	// Pushed pages (route handle `nav`) swap the brand header for a nav bar
	// on phones; tab roots keep it. Only signed-in pages have one.
	const navBarConfig = useNavBarConfig()
	const navBar = user ? navBarConfig : null
	// An edit screen (its route names the form the bar's Save submits) hides
	// the tab bar, as an iOS edit screen does: Cancel and Save are the ways
	// out. Its error page keeps it, an error after load included. The server
	// knows both, so the first paint has no tab bar to lose.
	const editScreen = useEditFormOnScreen(navBar?.form, navBar?.loaded ?? false)
	const toastTop = navBar
		? 'var(--nav-bar-bottom, calc(var(--safe-top) + 44px))'
		: 'var(--safe-top)'

	return (
		<NavTiming>
			<PostHogIdentify
				user={
					user
						? { id: user.id, name: user.name, username: user.username }
						: null
				}
				householdId={data.householdId}
				isDemo={data.demoExpiresAt != null}
			/>
			<PostHogPageview />
			<PostHogPwaLifecycle />
			<ServiceWorkerDataSync
				userId={user?.id ?? null}
				householdId={data.householdId}
			/>
			<ServiceWorkerUpdate />
			{isNativeShell ? (
				// The status bar sits on the chrome, so espresso needs light text.
				<NativeShellBridge theme={chrome === 'espresso' ? 'dark' : theme} />
			) : null}
			<OpenImgContextProvider
				optimizerEndpoint="/resources/images"
				breakpoints={[...IMAGE_BREAKPOINTS]}
				getSrc={getImgSrc}
			>
				<div
					className="flex min-h-screen flex-col justify-between"
					data-chrome={chrome}
				>
					{isNativeShell ? (
						// Content scrolls under the status bar behind the same opaque
						// background as the bottom tab bar.
						<div
							aria-hidden="true"
							data-status-bar-backdrop=""
							className="bg-card pointer-events-none fixed inset-x-0 top-0 z-50 h-(--safe-top) print:hidden"
						/>
					) : null}
					<header
						data-site-header=""
						data-pushed={navBar ? '' : undefined}
						data-edit-screen={editScreen ? '' : undefined}
						// A pushed page's bar stays pinned on phones too, opaque, so its
						// title has somewhere to show once the page's own scrolls away.
						className={cn(
							'border-border/50 z-40 border-b',
							navBar ? 'bg-card sticky top-0' : 'bg-card md:sticky md:top-0',
						)}
					>
						<DemoBanner />
						<nav
							aria-label="Main"
							// Signed in, the iOS app's row is as tall as a native nav bar
							// (44pt): the Settings link is 44pt itself.
							className={cn(
								'container flex flex-wrap items-center justify-between gap-4 sm:flex-nowrap md:gap-8',
								isNativeShell && user ? 'py-0' : 'py-3',
								// Phones have the tab bar; the desktop header keeps its links.
								navBar && 'max-md:hidden',
							)}
						>
							<Logo />
							<div className="ml-auto flex items-center gap-4 md:gap-10">
								{user ? (
									<>
										<div className="hidden items-center gap-2 md:flex">
											{navItems.map((item) => (
												<NavLink
													key={item.to}
													to={item.to}
													prefetch="intent"
													className={headerNavLinkClass}
												>
													{item.label}
												</NavLink>
											))}
										</div>
										<UserDropdown />
									</>
								) : (
									<HeaderAuthButton />
								)}
							</div>
						</nav>
						{navBar ? <NavBar {...navBar} /> : null}
					</header>

					<main id="main-content" className="flex flex-1 flex-col">
						<Outlet />
					</main>
				</div>
				<BottomNav hidden={editScreen} />
				<Toaster
					closeButton
					position="top-center"
					theme={theme}
					// Sonner's default offsets, pushed below the status bar in the iOS
					// app (the inset is 0 everywhere else), and below a pushed page's
					// pinned header (its nav bar on phones and on desktop edit screens).
					offset={{ top: `calc(24px + ${toastTop})` }}
					mobileOffset={{ top: `calc(16px + ${toastTop})` }}
				/>
				<UndoToaster theme={theme} />
				<OfflineIndicator />
				{user && isPro ? <HouseholdActivityNotifier /> : null}
				{user ? <ProExpiryNudge /> : null}
			</OpenImgContextProvider>
		</NavTiming>
	)
}

function headerNavLinkClass({ isActive }: { isActive: boolean }) {
	return cn(
		'rounded-full px-4 py-1.5 text-sm transition-colors duration-200',
		isActive
			? 'text-primary font-medium'
			: 'text-muted-foreground hover:text-primary',
	)
}

function Logo() {
	return (
		<Link to="/" className="group flex items-center gap-2">
			<span className="text-foreground font-sans text-xl font-medium tracking-tight">
				Quartermaster
			</span>
		</Link>
	)
}

function HeaderAuthButton() {
	const { pathname } = useLocation()
	const isLogin = pathname === '/login'
	return (
		<Button asChild variant="default" size="lg">
			<Link to={isLogin ? '/signup' : '/login'}>
				{isLogin ? 'Sign up' : 'Log in'}
			</Link>
		</Button>
	)
}

