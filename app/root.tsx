export async function loader({ request }: Route.LoaderArgs) {
	const timings = makeTimings('root loader')
	const userId = await time(() => getUserId(request), {
		timings,
		type: 'getUserId',
		desc: 'getUserId in root',
	})

	// These lookups are independent of each other — run them concurrently.
	// This loader runs on every forced revalidation, so its latency is
	// navigation latency. getUserId has already logged out an expired session,
	// so the refresh only ever extends a live one.
	const [user, tierInfo, member, toastResult, sessionCookie] =
		await Promise.all([
			userId
				? time(
						() =>
							prisma.user.findUnique({
								select: {
									id: true,
									name: true,
									username: true,
									demoExpiresAt: true,
								},
								where: { id: userId },
							}),
						{ timings, type: 'find user', desc: 'find user in root' },
					)
				: null,
			userId ? getUserTier(userId) : DEFAULT_TIER_INFO,
			userId
				? prisma.householdMember.findFirst({
						where: { userId },
						select: {
							household: { select: { id: true, name: true } },
						},
					})
				: null,
			getToast(request),
			userId ? refreshSessionIfNeeded(request) : null,
		])
	if (userId && !user) {
		// A session whose user is gone (the account was deleted): log it out.
		await logout({ request, redirectTo: '/' })
	}

	const householdId = member?.household.id ?? null
	const householdName = member?.household.name ?? null
	const { toast, headers: toastHeaders } = toastResult
	// The demo banner draws its first paint from the time left by this clock,
	// so a browser whose clock is off still shows the right time (DemoBanner).
	const demoExpiresAt = user?.demoExpiresAt ?? null
	return data(
		{
			user: user && { id: user.id, name: user.name, username: user.username },
			demoExpiresAt: demoExpiresAt?.toISOString() ?? null,
			demoMsLeft: demoExpiresAt
				? Math.max(0, demoExpiresAt.getTime() - Date.now())
				: null,
			tierInfo,
			householdId,
			householdName,
			requestInfo: {
				hints: getHints(request),
				origin: getAppOrigin(),
				path: new URL(request.url).pathname,
				isNativeShell: isNativeShell(request),
				userPrefs: {
					theme: getTheme(request),
				},
			},
			ENV: getEnv(),
			toast,
		},
		{
			headers: combineHeaders(
				{ 'Server-Timing': timings.toString() },
				toastHeaders,
				sessionCookie ? { 'set-cookie': sessionCookie } : null,
			),
		},
	)
}

/**
 * When to re-run the root loader. It provides mostly-static data (user, theme,
 * ENV).
 *
 * With single fetch (React Router 8.3), the router passes
 * `defaultShouldRevalidate: true` to every match on any navigation that is not
 * after a failed action, so deferring to it re-runs root on page-to-page
 * navigations too, back and forward included. Links that should skip root opt
 * out at the call site with `defaultShouldRevalidate={false}` (the bottom tab
 * bar does, between tabs).
 *
 * Revalidate when:
 * - A flash toast is pending (the `en_toast_pending` marker cookie set by
 *   `createToastHeaders`): the next root-loader run renders and clears it.
 *   The cookie covers a `redirectWithToast` that only changes the search
 *   (/upgrade?session_id=… to /upgrade), which the search rule below would
 *   otherwise skip.
 * - The router says so (`defaultShouldRevalidate`): page-to-page and back or
 *   forward navigations (see above), same-URL revalidation, forced
 *   revalidation (Set-Cookie redirects replayed as X-Remix-Revalidate,
 *   useRevalidator), and successful form submissions.
 *
 * Skip when:
 * - Search params change on the same page (filters, pagination) — root data
 *   doesn't depend on them.
 * - The router says so: a link that opts out, and after a failed (4xx)
 *   action, so a validation error doesn't re-run the root queries.
 */
export function shouldRevalidate({
	defaultShouldRevalidate,
	currentUrl,
	nextUrl,
}: {
	defaultShouldRevalidate: boolean
	currentUrl: URL
	nextUrl: URL
}) {
	// Offline, the root request would fail: the service worker never caches it,
	// and the error would replace the whole app with the root error page. Keep
	// the data the page has; a pending toast stays in its cookie until the next
	// root load online. Covers Retry, pull to refresh and live refreshes.
	if (typeof navigator !== 'undefined' && !navigator.onLine) return false
	// The offline notice's Retry reloads only the tab (see tab-retry.ts). A tab
	// tap that interrupts it is a navigation and follows the rules below.
	if (isTabRetry() && currentUrl.href === nextUrl.href) return false

	// A toast is waiting — never skip, whatever shape the navigation takes.
	if (hasPendingToastCookie()) return true

	// Search params changed on the same page (filters, pagination) — root data
	// doesn't depend on them, so skip even though the router defaults to true.
	// A pending toast can't be stranded here: it would have hit the marker
	// check above.
	if (
		currentUrl.pathname === nextUrl.pathname &&
		currentUrl.search !== nextUrl.search
	) {
		return false
	}

	// Otherwise defer to the router: false after failed (4xx) actions and when a
	// link opts out, true otherwise (see above), including same-URL
	// revalidation, forced revalidation and successful submissions.
	return defaultShouldRevalidate
}

